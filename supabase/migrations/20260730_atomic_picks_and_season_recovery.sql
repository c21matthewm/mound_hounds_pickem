create or replace function public.import_season_restore_point(p_document jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  checksum_value text;
  computed_checksum text;
  inserted_point public.season_restore_points%rowtype;
  local_season public.league_seasons%rowtype;
  row_counts_value jsonb;
  schema_version_value text;
  season_year_value integer;
  snapshot_value jsonb;
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Admin access required.';
  end if;

  if p_document->>'format' <> 'mound-hounds-season-backup'
    or coalesce((p_document->>'formatVersion')::integer, 0) <> 1 then
    raise exception 'This is not a supported Mound Hounds season backup.';
  end if;

  snapshot_value := p_document->'snapshot';
  checksum_value := lower(trim(coalesce(p_document->>'checksum', '')));
  if jsonb_typeof(snapshot_value) <> 'object' or length(checksum_value) <> 64 then
    raise exception 'Backup snapshot or checksum is missing.';
  end if;

  computed_checksum := encode(
    extensions.digest(convert_to(snapshot_value::text, 'UTF8'), 'sha256'),
    'hex'
  );
  if computed_checksum <> checksum_value then
    raise exception 'Backup checksum validation failed. The file may be incomplete or edited.';
  end if;

  season_year_value := (snapshot_value->'season'->>'season_year')::integer;
  select * into local_season
  from public.league_seasons
  where season_year = season_year_value;
  if local_season.id is null then
    raise exception 'Create the % league season before importing this backup.', season_year_value;
  end if;

  row_counts_value := public.season_recovery_row_counts(snapshot_value);
  schema_version_value := coalesce(p_document->>'schemaVersion', 'unknown');

  insert into public.season_restore_points (
    season_id,
    season_year,
    label,
    source,
    schema_version,
    format_version,
    row_counts,
    snapshot,
    checksum,
    created_by
  )
  values (
    local_season.id,
    season_year_value,
    left(
      coalesce(nullif(trim(p_document->>'label'), ''), 'Uploaded season backup'),
      160
    ),
    'uploaded',
    schema_version_value,
    1,
    row_counts_value,
    snapshot_value,
    checksum_value,
    auth.uid()
  )
  returning * into inserted_point;

  perform public.write_admin_audit_event(
    'import_season_restore_point',
    'league_season',
    local_season.id::text,
    format('Validated and imported a %s season backup.', season_year_value),
    null,
    jsonb_build_object(
      'restore_point_id', inserted_point.id,
      'checksum', checksum_value,
      'row_counts', row_counts_value
    )
  );

  return jsonb_build_object(
    'id', inserted_point.id,
    'seasonId', inserted_point.season_id,
    'seasonYear', inserted_point.season_year,
    'label', inserted_point.label,
    'source', inserted_point.source,
    'schemaVersion', inserted_point.schema_version,
    'formatVersion', inserted_point.format_version,
    'rowCounts', inserted_point.row_counts,
    'checksum', inserted_point.checksum,
    'createdAt', inserted_point.created_at
  );
end;
$$;

revoke all on function public.import_season_restore_point(jsonb)
from public, anon;
