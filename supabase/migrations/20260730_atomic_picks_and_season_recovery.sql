from public, anon, authenticated;

create or replace function public.create_season_restore_point(
  p_season_id bigint,
  p_label text,
  p_source text default 'manual'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  checksum_value text;
  inserted_point public.season_restore_points%rowtype;
  row_counts_value jsonb;
  schema_version_value text;
  selected_season public.league_seasons%rowtype;
  snapshot_value jsonb;
begin
  if coalesce(auth.role(), '') <> 'service_role' and not public.is_admin(auth.uid()) then
    raise exception 'Admin access required.';
  end if;

  if p_source not in ('automatic', 'manual', 'pre_restore', 'uploaded') then
    raise exception 'Invalid restore-point source.';
  end if;

  if length(trim(coalesce(p_label, ''))) not between 1 and 160 then
    raise exception 'Restore-point label must be between 1 and 160 characters.';
  end if;

  select * into selected_season
  from public.league_seasons
  where id = p_season_id;

  if selected_season.id is null then
    raise exception 'Selected season was not found.';
  end if;

  snapshot_value := public.build_season_recovery_snapshot(selected_season.id);
  row_counts_value := public.season_recovery_row_counts(snapshot_value);
  select value into schema_version_value
  from public.app_metadata
  where key = 'schema_version';
  schema_version_value := coalesce(schema_version_value, 'unknown');
  checksum_value := encode(
    extensions.digest(convert_to(snapshot_value::text, 'UTF8'), 'sha256'),
    'hex'
  );

  insert into public.season_restore_points (
    season_id,
    season_year,
    label,
    source,
    schema_version,
    row_counts,
    snapshot,
    checksum,
    created_by
  )
  values (
    selected_season.id,
    selected_season.season_year,
    trim(p_label),
    p_source,
    schema_version_value,
    row_counts_value,
    snapshot_value,
    checksum_value,
    auth.uid()
  )
  returning * into inserted_point;

  perform public.write_admin_audit_event(
    'create_season_restore_point',
    'league_season',
    selected_season.id::text,
    format('Created %s recovery point: %s.', p_source, trim(p_label)),
    null,
    jsonb_build_object(
      'restore_point_id', inserted_point.id,
      'checksum', checksum_value,
      'row_counts', row_counts_value
    )
  );

  return jsonb_build_object(
    'id', inserted_point.id,
    'seasonId', inserted_point.season_id,
    'seasonYear', inserted_point.season_year,
    'label', inserted_point.label,
    'source', inserted_point.source,
    'schemaVersion', inserted_point.schema_version,
    'formatVersion', inserted_point.format_version,
    'rowCounts', inserted_point.row_counts,
    'checksum', inserted_point.checksum,
    'createdAt', inserted_point.created_at
  );
end;
$$;

revoke all on function public.create_season_restore_point(bigint, text, text)
from public, anon;
grant execute on function public.create_season_restore_point(bigint, text, text)
to authenticated, service_role;

create or replace function public.create_restore_point_after_result_publication()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.results_status = 'published'
    and (
      old.results_status is distinct from new.results_status
      or old.results_published_at is distinct from new.results_published_at
    ) then
    perform public.create_season_restore_point(
      new.season_id,
      format('After R%s results: %s', new.round_number, new.race_name),
      'automatic'
    );
  end if;

  return new;
end;
$$;

