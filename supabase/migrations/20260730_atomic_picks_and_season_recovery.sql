create or replace function public.record_pick_submission_version()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  next_version integer;
begin
  if current_setting('mound_hounds.restore_mode', true) = 'on' then
    return new;
  end if;

  select coalesce(max(version.submission_version), 0) + 1
  into next_version
  from public.pick_submission_versions version
  where version.user_id = new.user_id
    and version.race_id = new.race_id;

  insert into public.pick_submission_versions (
    pick_id,
    user_id,
    race_id,
    submission_version,
    average_speed,
    driver_group1_id,
    driver_group2_id,
    driver_group3_id,
    driver_group4_id,
    driver_group5_id,
    driver_group6_id,
    driver_group7_id,
    driver_group8_id,
    submitted_at
  )
  values (
    new.id,
    new.user_id,
    new.race_id,
    next_version,
    new.average_speed,
    new.driver_group1_id,
    new.driver_group2_id,
    new.driver_group3_id,
    new.driver_group4_id,
    new.driver_group5_id,
    new.driver_group6_id,
    new.driver_group7_id,
    new.driver_group8_id,
    new.updated_at
  );

  return new;
end;
$$;

