alter table public.league_seasons enable row level security;

grant select, insert, update, delete on table public.league_seasons to authenticated;
grant usage, select on sequence public.league_seasons_id_seq to authenticated;

drop policy if exists league_seasons_read_authenticated on public.league_seasons;
create policy league_seasons_read_authenticated
