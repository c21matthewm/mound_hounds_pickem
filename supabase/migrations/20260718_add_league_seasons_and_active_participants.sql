-- Add explicit league seasons, race rounds, participant activity, and season-aware driver points.

begin;

create table if not exists public.league_seasons (
  id bigint generated by default as identity primary key,
  season_year integer not null unique check (season_year between 2000 and 2100),
  display_name text not null check (length(trim(display_name)) > 0),
  status text not null default 'upcoming' check (status in ('upcoming', 'active', 'completed')),
  activated_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create unique index if not exists idx_league_seasons_single_active
on public.league_seasons(status)
where status = 'active';

create index if not exists idx_league_seasons_year
on public.league_seasons(season_year desc);

drop trigger if exists trg_league_seasons_updated_at on public.league_seasons;
create trigger trg_league_seasons_updated_at
before update on public.league_seasons
for each row execute function public.set_updated_at();

with race_years as (
  select distinct
    extract(year from race_date at time zone 'America/Indiana/Indianapolis')::integer as season_year
  from public.races
),
current_league_year as (
  select extract(year from timezone('America/Indiana/Indianapolis', now()))::integer as season_year
)
insert into public.league_seasons (season_year, display_name, status, activated_at, completed_at)
select
  race_years.season_year,
  race_years.season_year::text,
  case
    when race_years.season_year = current_league_year.season_year then 'active'
    when race_years.season_year < current_league_year.season_year then 'completed'
    else 'upcoming'
  end,
  case when race_years.season_year = current_league_year.season_year then timezone('utc', now()) end,
  case when race_years.season_year < current_league_year.season_year then timezone('utc', now()) end
from race_years
cross join current_league_year
on conflict (season_year) do nothing;

alter table public.races
add column if not exists season_id bigint references public.league_seasons(id) on delete restrict;

alter table public.races
add column if not exists round_number smallint;

update public.races race
set season_id = season.id
from public.league_seasons season
where race.season_id is null
  and season.season_year =
    extract(year from race.race_date at time zone 'America/Indiana/Indianapolis')::integer;

update public.races
set round_number = substring(race_name from '(?i)^\s*Race\s+([0-9]+)\s*-\s*')::smallint
where round_number is null
  and race_name ~* '^\s*Race\s+[0-9]+\s*-\s*';

with existing_rounds as (
  select season_id, coalesce(max(round_number), 0) as maximum_round
  from public.races
  group by season_id
),
unnumbered as (
  select
    race.id,
    existing_rounds.maximum_round + row_number() over (
      partition by race.season_id
      order by race.race_date asc, race.id asc
    ) as inferred_round
  from public.races race
  join existing_rounds on existing_rounds.season_id = race.season_id
  where race.round_number is null
)
update public.races race
set round_number = unnumbered.inferred_round::smallint
from unnumbered
where race.id = unnumbered.id;

update public.races
set race_name = trim(regexp_replace(race_name, '^\s*Race\s+[0-9]+\s*-\s*', '', 'i'))
where race_name ~* '^\s*Race\s+[0-9]+\s*-\s*';

alter table public.races
alter column season_id set not null;

alter table public.races
alter column round_number set not null;

alter table public.races
drop constraint if exists races_round_number_check;

alter table public.races
add constraint races_round_number_check check (round_number between 1 and 99);

alter table public.races
drop constraint if exists races_season_round_unique;

alter table public.races
add constraint races_season_round_unique unique (season_id, round_number);

create index if not exists idx_races_season_round
on public.races(season_id, round_number);

create index if not exists idx_races_season_status
on public.races(season_id, is_archived, results_status, round_number);

create or replace function public.assign_race_season_and_round()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.season_id is null then
    select season.id into new.season_id
    from public.league_seasons season
    where season.status = 'active';
  end if;

  if new.season_id is null then
    raise exception 'Create or activate a league season before adding races.';
  end if;

  if new.round_number is null then
    select (coalesce(max(race.round_number), 0) + 1)::smallint into new.round_number
    from public.races race
    where race.season_id = new.season_id;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_assign_race_season_and_round on public.races;
create trigger trg_assign_race_season_and_round
before insert on public.races
for each row execute function public.assign_race_season_and_round();

alter table public.profiles
add column if not exists is_active boolean not null default true;

create index if not exists idx_profiles_active_team
on public.profiles(is_active, team_name);

create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.role() = 'authenticated' and not public.is_admin(auth.uid()) then
    if tg_op = 'INSERT' and (new.role <> 'participant' or new.is_active <> true) then
      raise exception 'Only an administrator may assign protected profile fields.';
    end if;

    if tg_op = 'UPDATE' and (
      new.role is distinct from old.role
      or new.is_active is distinct from old.is_active
    ) then
      raise exception 'Only an administrator may change protected profile fields.';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_protect_profile_role on public.profiles;
create trigger trg_protect_profile_role
before insert or update of role, is_active on public.profiles
for each row execute function public.protect_profile_role();

revoke all on function public.protect_profile_role() from public;

alter table public.drivers
add column if not exists opening_seed_standing integer;

update public.drivers
set opening_seed_standing = current_standing
where opening_seed_standing is null;

alter table public.drivers
