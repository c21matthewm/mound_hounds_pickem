create or replace function public.activate_league_season(p_season_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_season public.league_seasons%rowtype;
  target_season public.league_seasons%rowtype;
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Only an admin can activate a league season.';
  end if;

  select * into target_season
  from public.league_seasons
  where id = p_season_id
  for update;

  if target_season.id is null then
    raise exception 'Selected season was not found.';
  end if;

  if target_season.status = 'completed' then
    raise exception 'A completed season cannot be reactivated.';
  end if;

  if not exists (
    select 1
    from public.races race
    where race.season_id = target_season.id
      and race.is_archived = false
  ) then
    raise exception 'Add at least one race to the target season before activating it.';
  end if;

  select * into current_season
  from public.league_seasons
  where status = 'active'
  for update;

  if current_season.id = target_season.id then
    return;
  end if;

  if current_season.id is not null and not exists (
    select 1
    from public.hall_of_fame_seasons hall
    where hall.season_year = current_season.season_year
  ) then
    raise exception 'Finalize the % Hall of Fame standings before activating a new season.', current_season.season_year;
  end if;

  if current_season.id is not null then
    update public.league_seasons
    set status = 'completed', completed_at = timezone('utc', now())
    where id = current_season.id;
  end if;

  update public.drivers
  set
    opening_seed_standing = current_standing,
    championship_points = 0
  where is_active = true;

  update public.league_seasons
  set
    status = 'active',
    activated_at = timezone('utc', now()),
    completed_at = null
  where id = target_season.id;
end;
$$;

revoke all on function public.activate_league_season(bigint) from public, anon;
grant execute on function public.activate_league_season(bigint) to authenticated;

create or replace function public.refresh_driver_standings_from_published_results()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  active_driver_count integer;
  active_season_id bigint;
  published_race_count integer;
begin
  if coalesce(auth.role(), '') <> 'service_role' and not public.is_admin(auth.uid()) then
    raise exception 'Admin access required.';
  end if;

  select id into active_season_id
  from public.league_seasons
  where status = 'active';

  if active_season_id is null then
    raise exception 'No active league season is configured.';
  end if;

  select count(*) into published_race_count
  from public.races race
  where race.season_id = active_season_id
    and race.is_archived = false
    and race.results_status = 'published';

  update public.drivers driver
  set championship_points = coalesce(points_by_driver.total_points, 0)
  from (
    select
      candidate.id as driver_id,
      coalesce(sum(result_row.points) filter (
        where race.season_id = active_season_id
          and race.is_archived = false
          and race.results_status = 'published'
      ), 0)::integer as total_points
    from public.drivers candidate
    left join public.results result_row on result_row.driver_id = candidate.id
    left join public.races race on race.id = result_row.race_id
    group by candidate.id
  ) points_by_driver
  where driver.id = points_by_driver.driver_id;

  with ranked_active as (
    select
      driver.id,
      row_number() over (
        order by
          case when published_race_count > 0 then driver.championship_points end desc,
          driver.opening_seed_standing asc nulls last,
          driver.current_standing asc,
          driver.driver_name asc
      )::integer as next_standing
    from public.drivers driver
    where driver.is_active = true
  )
  update public.drivers driver
  set
    current_standing = ranked_active.next_standing,
    group_number = case
      when ranked_active.next_standing <= 4 then 1
      when ranked_active.next_standing <= 8 then 2
      when ranked_active.next_standing <= 12 then 3
      when ranked_active.next_standing <= 16 then 4
      when ranked_active.next_standing <= 20 then 5
      else 6
    end
  from ranked_active
  where driver.id = ranked_active.id;

  select count(*) into active_driver_count
  from public.drivers driver
  where driver.is_active = true;

  with ranked_inactive as (
    select
      driver.id,
      (active_driver_count + row_number() over (
        order by driver.current_standing asc, driver.driver_name asc
      ))::integer as next_standing
    from public.drivers driver
    where driver.is_active = false
  )
  update public.drivers driver
  set
    current_standing = ranked_inactive.next_standing,
    group_number = 6
  from ranked_inactive
  where driver.id = ranked_inactive.id;
end;
$$;

revoke all on function public.refresh_driver_standings_from_published_results() from public, anon;
grant execute on function public.refresh_driver_standings_from_published_results() to authenticated, service_role;

create or replace function public.enforce_pick_deadline()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  previous_race_name text;
  previous_results_status text;
  race_is_archived boolean;
  race_pick_format text;
  race_qualifying_start_at timestamptz;
  race_round_number smallint;
  race_season_id bigint;
  race_start_at timestamptz;
  pick_lock_at timestamptz;
begin
  select
    race.qualifying_start_at,
    race.race_date,
    race.is_archived,
    race.pick_format,
    race.season_id,
    race.round_number
  into
    race_qualifying_start_at,
    race_start_at,
    race_is_archived,
    race_pick_format,
    race_season_id,
    race_round_number
  from public.races race
  where race.id = new.race_id;

  if race_qualifying_start_at is null or race_start_at is null then
    raise exception 'Race not found for pick submission';
  end if;

  if race_is_archived then
    raise exception 'Picks are disabled for archived races.';
  end if;

  if not exists (
    select 1
    from public.profiles profile
    where profile.id = new.user_id
      and profile.is_active = true
  ) then
    raise exception 'Your participant profile is inactive for the current season.';
  end if;

  if not exists (
    select 1
    from public.league_seasons season
    where season.id = race_season_id
      and season.status = 'active'
  ) then
    raise exception 'Picks are only accepted for the active league season.';
  end if;

  select previous_race.race_name, previous_race.results_status
  into previous_race_name, previous_results_status
  from public.races previous_race
  where previous_race.is_archived = false
    and previous_race.season_id = race_season_id
    and previous_race.round_number < race_round_number
  order by previous_race.round_number desc
  limit 1;

  if previous_race_name is not null and previous_results_status <> 'published' then
    raise exception 'Picks are unavailable until % results are published.', previous_race_name;
  end if;

  pick_lock_at := case
    when race_pick_format = 'indy_500' then race_start_at
    else race_qualifying_start_at
  end;

  if timezone('utc', now()) >= pick_lock_at then
    if race_pick_format = 'indy_500' then
      raise exception 'Picks are locked because the race has already started.';
    end if;
    raise exception 'Picks are locked because qualifying has already started.';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_enforce_pick_deadline on public.picks;
create trigger trg_enforce_pick_deadline
before insert or update on public.picks
for each row execute function public.enforce_pick_deadline();

commit;
