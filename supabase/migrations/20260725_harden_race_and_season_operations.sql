to authenticated;

create or replace function public.require_invite_code_before_season_activation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'active'
    and (tg_op = 'INSERT' or old.status is distinct from 'active')
    and not exists (
      select 1
      from public.season_registration_secrets secret
      where secret.season_id = new.id
    ) then
    raise exception 'Set the season invite code before activating registration.';
  end if;

  if new.status = 'active'
    and (tg_op = 'INSERT' or old.status is distinct from 'active')
    and new.roster_configured_at is null then
    raise exception 'Import the opening driver roster before activating the season.';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_require_invite_code_before_season_activation
on public.league_seasons;
create trigger trg_require_invite_code_before_season_activation
before insert or update of status on public.league_seasons
for each row execute function public.require_invite_code_before_season_activation();

create or replace function public.register_profile_for_season_with_code(
  p_profile_id uuid,
  p_season_id bigint,
  p_invite_code text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_profile public.profiles%rowtype;
  registration_secret public.season_registration_secrets%rowtype;
  selected_season public.league_seasons%rowtype;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Service role required.';
  end if;

  select * into current_profile
  from public.profiles
  where id = p_profile_id;

  if current_profile.id is null then
    raise exception 'Participant profile was not found.';
  end if;

  if current_profile.is_active = false then
    raise exception 'This account is not eligible for league participation.';
  end if;

  select * into selected_season
  from public.league_seasons
  where id = p_season_id;

  if selected_season.id is null or selected_season.status <> 'active' then
    raise exception 'Registration is only available for the active league season.';
  end if;

  if exists (
    select 1
    from public.season_participants participant
    where participant.season_id = p_season_id
      and participant.profile_id = p_profile_id
      and participant.status = 'registered'
  ) then
    return;
  end if;

  select * into registration_secret
  from public.season_registration_secrets
  where season_id = p_season_id;

  if registration_secret.season_id is null then
    raise exception 'Registration is not open yet. The league admin must configure the season invite code.';
  end if;

  if extensions.crypt(
    trim(coalesce(p_invite_code, '')),
    registration_secret.invite_code_hash
  )
    <> registration_secret.invite_code_hash then
    raise exception 'The season invite code is incorrect.';
  end if;

  insert into public.season_participants (
    season_id,
    profile_id,
    status,
    registered_at,
    decided_at
  )
  values (
    p_season_id,
    p_profile_id,
    'registered',
    timezone('utc', now()),
    timezone('utc', now())
  )
  on conflict (season_id, profile_id) do update
  set
    status = 'registered',
    registered_at = coalesce(public.season_participants.registered_at, excluded.registered_at),
    decided_at = excluded.decided_at;
end;
$$;

revoke all on function public.register_profile_for_season_with_code(uuid, bigint, text)
