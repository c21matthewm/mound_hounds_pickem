create or replace function public.validate_pick_groups()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_driver_ids bigint[];
  distinct_count integer;
  group_index integer;
  selected_driver_id bigint;
  race_pick_format text;
  expected_group_count integer;
begin
  select race.pick_format into race_pick_format
  from public.races race
  where race.id = new.race_id;

  if race_pick_format is null then
    raise exception 'Race not found for pick validation';
  end if;

  perform public.ensure_race_pick_field_snapshot(new.race_id);

  expected_group_count := case when race_pick_format = 'indy_500' then 8 else 6 end;
  selected_driver_ids := (array[
    new.driver_group1_id,
    new.driver_group2_id,
    new.driver_group3_id,
    new.driver_group4_id,
    new.driver_group5_id,
    new.driver_group6_id,
    new.driver_group7_id,
    new.driver_group8_id
  ])[1:expected_group_count];

  if race_pick_format = 'indy_500'
    and (new.driver_group7_id is null or new.driver_group8_id is null) then
    raise exception 'Indianapolis 500 picks require one driver from each of 8 groups';
  end if;

  if race_pick_format <> 'indy_500'
    and (new.driver_group7_id is not null or new.driver_group8_id is not null) then
    raise exception 'Standard race picks must contain exactly 6 drivers';
  end if;

  for group_index in 1..expected_group_count loop
    selected_driver_id := selected_driver_ids[group_index];

    if not exists (
      select 1
      from public.race_driver_groups race_group
      where race_group.race_id = new.race_id
        and race_group.driver_id = selected_driver_id
        and race_group.group_number = group_index
    ) then
      raise exception 'Invalid Group % driver for the frozen race field', group_index;
    end if;
  end loop;

  select count(distinct driver_id) into distinct_count
  from unnest(selected_driver_ids) as selected(driver_id);

  if distinct_count <> expected_group_count then
    raise exception 'Each pick must contain % distinct drivers', expected_group_count;
  end if;

  return new;
end;
$$;

