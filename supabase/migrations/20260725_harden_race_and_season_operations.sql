create or replace function public.replace_indy_500_qualifying_order(
  p_race_id bigint,
  p_rows jsonb
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted_count integer;
  selected_race public.races%rowtype;
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Only an admin can replace qualifying order.';
  end if;

  select * into selected_race
  from public.races
  where id = p_race_id
  for update;

  if selected_race.id is null then
    raise exception 'Selected race was not found.';
  end if;

  if selected_race.is_archived or selected_race.pick_format <> 'indy_500' then
    raise exception 'Select an active Indianapolis 500 race.';
  end if;

  if selected_race.field_frozen_at is not null
    or exists (select 1 from public.picks where race_id = p_race_id)
    or exists (select 1 from public.results where race_id = p_race_id) then
    raise exception 'Qualifying groups are locked because the race field, picks, or results already exist.';
  end if;

  if jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) <> 33 then
    raise exception 'Indianapolis 500 qualifying order must contain exactly 33 drivers.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_rows)
      as row_data(driver_id bigint, group_number integer, qualifying_position integer)
    where row_data.driver_id is null
      or row_data.group_number not between 1 and 8
      or row_data.qualifying_position not between 1 and 33
      or row_data.group_number <> least(
        8,
        (((row_data.qualifying_position - 1) / 4) + 1)
      )
  ) then
    raise exception 'Qualifying payload contains invalid drivers, groups, or positions.';
  end if;

  if (
    select count(distinct row_data.driver_id)
    from jsonb_to_recordset(p_rows)
      as row_data(driver_id bigint, group_number integer, qualifying_position integer)
  ) <> 33 or (
    select count(distinct row_data.qualifying_position)
    from jsonb_to_recordset(p_rows)
      as row_data(driver_id bigint, group_number integer, qualifying_position integer)
  ) <> 33 then
    raise exception 'Qualifying drivers and positions must be unique.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_rows)
      as row_data(driver_id bigint, group_number integer, qualifying_position integer)
    left join public.drivers driver on driver.id = row_data.driver_id
    where driver.id is null
  ) then
    raise exception 'Qualifying payload contains an unknown driver.';
  end if;

  delete from public.race_driver_groups
  where race_id = p_race_id;

  insert into public.race_driver_groups (
    race_id,
    driver_id,
    group_number,
    qualifying_position
  )
  select
    p_race_id,
    row_data.driver_id,
    row_data.group_number,
    row_data.qualifying_position
  from jsonb_to_recordset(p_rows)
    as row_data(driver_id bigint, group_number integer, qualifying_position integer);

  get diagnostics inserted_count = row_count;

  perform public.write_admin_audit_event(
    'replace_qualifying_order',
    'race',
    p_race_id::text,
    format('Imported %s Indianapolis 500 qualifying rows.', inserted_count),
    null,
    jsonb_build_object('qualifying_row_count', inserted_count)
  );

  return inserted_count;
end;
$$;

revoke all on function public.replace_indy_500_qualifying_order(bigint, jsonb)
from public, anon;
grant execute on function public.replace_indy_500_qualifying_order(bigint, jsonb)
to authenticated;

create or replace function public.ensure_race_pick_field_snapshot(p_race_id bigint)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_race public.races%rowtype;
  snapshot_count integer;
begin
  select * into selected_race
  from public.races
  where id = p_race_id
  for update;

  if selected_race.id is null then
    raise exception 'Selected race was not found.';
  end if;

  if selected_race.is_archived then
    raise exception 'Archived races cannot open a pick field.';
  end if;

  if selected_race.field_frozen_at is null then
    if selected_race.pick_format = 'standard' then
      insert into public.race_driver_groups (
        race_id,
        driver_id,
        group_number,
        qualifying_position
      )
      select
        selected_race.id,
        driver.id,
        driver.group_number,
        null
      from public.drivers driver
      where driver.is_active = true
      on conflict (race_id, driver_id) do nothing;
    end if;

    select count(*)::integer into snapshot_count
    from public.race_driver_groups
    where race_id = selected_race.id;

    if selected_race.pick_format = 'indy_500' and snapshot_count <> 33 then
      raise exception 'Import the complete 33-driver qualifying order before opening Indianapolis 500 picks.';
    end if;

    if selected_race.pick_format = 'standard' and (
      snapshot_count < 6 or exists (
        select group_number
        from generate_series(1, 6) as expected(group_number)
        where not exists (
          select 1
          from public.race_driver_groups race_group
          where race_group.race_id = selected_race.id
            and race_group.group_number = expected.group_number
        )
      )
    ) then
      raise exception 'Every standard pick group must contain at least one active driver before picks can open.';
    end if;

    update public.races
    set field_frozen_at = timezone('utc', now())
    where id = selected_race.id;
  else
    select count(*)::integer into snapshot_count
    from public.race_driver_groups
    where race_id = selected_race.id;
  end if;

  return snapshot_count;
end;
$$;

revoke all on function public.ensure_race_pick_field_snapshot(bigint) from public, anon;
grant execute on function public.ensure_race_pick_field_snapshot(bigint)
to service_role;

