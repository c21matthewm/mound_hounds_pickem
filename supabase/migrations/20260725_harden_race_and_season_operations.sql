-- Harden season registration, race-week field snapshots, and administrative operations.

begin;

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

alter table public.league_seasons
add column if not exists registration_code_configured_at timestamptz,
add column if not exists roster_configured_at timestamptz,
add column if not exists rules_document_url text;

update public.league_seasons
set roster_configured_at = coalesce(roster_configured_at, timezone('utc', now()))
where status = 'active';

alter table public.races
add column if not exists field_frozen_at timestamptz;

alter table public.picks
drop constraint if exists picks_average_speed_check;

alter table public.picks
add constraint picks_average_speed_check check (average_speed > 0 and average_speed <= 300);

alter table public.races
drop constraint if exists races_official_winning_average_speed_nonnegative;

alter table public.races
drop constraint if exists races_official_winning_average_speed_check;

alter table public.races
add constraint races_official_winning_average_speed_check
check (
  official_winning_average_speed is null
  or (
    official_winning_average_speed > 0
    and official_winning_average_speed <= 300
  )
);

create table if not exists public.season_registration_secrets (
  season_id bigint primary key references public.league_seasons(id) on delete cascade,
  invite_code_hash text not null,
  updated_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.admin_audit_events (
  id bigint generated by default as identity primary key,
  actor_profile_id uuid references public.profiles(id) on delete set null,
  action text not null check (length(trim(action)) > 0),
  entity_type text not null check (length(trim(entity_type)) > 0),
  entity_id text,
  summary text not null check (length(trim(summary)) > 0),
  before_state jsonb,
  after_state jsonb,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.job_runs (
  id bigint generated by default as identity primary key,
  job_name text not null check (job_name in ('pick-reminders', 'fantasy-winner')),
  status text not null default 'running' check (status in ('running', 'succeeded', 'failed')),
  summary jsonb not null default '{}'::jsonb check (jsonb_typeof(summary) = 'object'),
  error_message text,
  started_at timestamptz not null default timezone('utc', now()),
  completed_at timestamptz,
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_admin_audit_events_created
on public.admin_audit_events(created_at desc);

create index if not exists idx_admin_audit_events_entity
on public.admin_audit_events(entity_type, entity_id, created_at desc);

create index if not exists idx_job_runs_job_started
on public.job_runs(job_name, started_at desc);

drop trigger if exists trg_season_registration_secrets_updated_at
on public.season_registration_secrets;
create trigger trg_season_registration_secrets_updated_at
before update on public.season_registration_secrets
for each row execute function public.set_updated_at();

alter table public.season_registration_secrets enable row level security;
alter table public.admin_audit_events enable row level security;
alter table public.job_runs enable row level security;

revoke all on table public.season_registration_secrets from public, anon, authenticated;
grant select on table public.admin_audit_events to authenticated;
grant select on table public.job_runs to authenticated;

drop policy if exists admin_audit_events_admin_read on public.admin_audit_events;
create policy admin_audit_events_admin_read
on public.admin_audit_events
for select
to authenticated
using (public.is_admin(auth.uid()));

drop policy if exists job_runs_admin_read on public.job_runs;
create policy job_runs_admin_read
on public.job_runs
for select
to authenticated
using (public.is_admin(auth.uid()));

create or replace function public.write_admin_audit_event(
  p_action text,
  p_entity_type text,
  p_entity_id text,
  p_summary text,
  p_before_state jsonb default null,
  p_after_state jsonb default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted_id bigint;
begin
  if coalesce(auth.role(), '') <> 'service_role' and not public.is_admin(auth.uid()) then
    raise exception 'Admin access required.';
  end if;

  insert into public.admin_audit_events (
    actor_profile_id,
    action,
    entity_type,
    entity_id,
    summary,
    before_state,
    after_state
  )
  values (
    auth.uid(),
    trim(p_action),
    trim(p_entity_type),
    nullif(trim(coalesce(p_entity_id, '')), ''),
    trim(p_summary),
    p_before_state,
    p_after_state
  )
  returning id into inserted_id;

  return inserted_id;
end;
$$;

revoke all on function public.write_admin_audit_event(text, text, text, text, jsonb, jsonb)
from public, anon;
grant execute on function public.write_admin_audit_event(text, text, text, text, jsonb, jsonb)
to authenticated, service_role;

create or replace function public.create_league_season(
  p_season_year integer,
  p_invite_code text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  invite_code text := trim(coalesce(p_invite_code, ''));
  inserted_season_id bigint;
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Only an admin can create a league season.';
  end if;

  if p_season_year < 2000 or p_season_year > 2100 then
    raise exception 'Enter a valid four-digit season year.';
  end if;

  if length(invite_code) < 8 or length(invite_code) > 64 then
    raise exception 'Season invite code must be between 8 and 64 characters.';
  end if;

  insert into public.league_seasons (
    season_year,
    display_name,
    status,
    registration_code_configured_at
  )
  values (
    p_season_year,
    p_season_year::text,
    'upcoming',
    timezone('utc', now())
  )
  returning id into inserted_season_id;

  insert into public.season_registration_secrets (
    season_id,
    invite_code_hash,
    updated_by
  )
  values (
    inserted_season_id,
    extensions.crypt(invite_code, extensions.gen_salt('bf', 10)),
    auth.uid()
  );

  perform public.write_admin_audit_event(
    'create',
    'league_season',
    inserted_season_id::text,
    format('Created %s season with a registration code.', p_season_year),
    null,
    jsonb_build_object('season_year', p_season_year, 'status', 'upcoming')
  );

  return inserted_season_id;
end;
$$;

revoke all on function public.create_league_season(integer, text)
from public, anon;
grant execute on function public.create_league_season(integer, text)
to authenticated;

create or replace function public.set_league_season_invite_code(
  p_season_id bigint,
  p_invite_code text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  invite_code text := trim(coalesce(p_invite_code, ''));
  selected_season public.league_seasons%rowtype;
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Only an admin can change a season invite code.';
  end if;

  if length(invite_code) < 8 or length(invite_code) > 64 then
    raise exception 'Season invite code must be between 8 and 64 characters.';
  end if;

  select * into selected_season
  from public.league_seasons
  where id = p_season_id
  for update;

  if selected_season.id is null then
    raise exception 'Selected season was not found.';
  end if;

  if selected_season.status = 'completed' then
    raise exception 'The invite code for a completed season cannot be changed.';
  end if;

  insert into public.season_registration_secrets (
    season_id,
    invite_code_hash,
    updated_by
  )
  values (
    p_season_id,
    extensions.crypt(invite_code, extensions.gen_salt('bf', 10)),
    auth.uid()
  )
  on conflict (season_id) do update
  set
    invite_code_hash = excluded.invite_code_hash,
    updated_by = excluded.updated_by;

  update public.league_seasons
  set registration_code_configured_at = timezone('utc', now())
  where id = p_season_id;

  perform public.write_admin_audit_event(
    'update_invite_code',
    'league_season',
    p_season_id::text,
    format('Updated the %s season registration code.', selected_season.season_year)
  );
end;
$$;

revoke all on function public.set_league_season_invite_code(bigint, text)
