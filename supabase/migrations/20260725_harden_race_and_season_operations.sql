create or replace function public.set_active_season_participation(p_register boolean)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  active_season_id bigint;
  current_profile public.profiles%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Authentication required.';
  end if;

  select * into current_profile
  from public.profiles
  where id = auth.uid();

  if current_profile.id is null
    or length(trim(coalesce(current_profile.full_name, ''))) = 0
    or length(trim(coalesce(current_profile.team_name, ''))) = 0 then
    raise exception 'Complete your profile before choosing a season.';
  end if;

  if current_profile.is_active = false then
    raise exception 'This account is not eligible for league participation.';
  end if;

  select id into active_season_id
  from public.league_seasons
  where status = 'active';

  if active_season_id is null then
    raise exception 'No league season is currently open for registration.';
  end if;

  if p_register then
    if exists (
      select 1
      from public.season_participants participant
      where participant.season_id = active_season_id
        and participant.profile_id = auth.uid()
        and participant.status = 'registered'
    ) then
      return active_season_id;
    end if;

    raise exception 'Enter the season invite code to register.';
  end if;

  if exists (
    select 1
    from public.picks pick
    join public.races race on race.id = pick.race_id
    where pick.user_id = auth.uid()
      and race.season_id = active_season_id
  ) then
    raise exception 'A team with submitted picks cannot leave the active season.';
  end if;

  insert into public.season_participants (
    season_id,
    profile_id,
    status,
    registered_at,
    decided_at
  )
  values (
    active_season_id,
    auth.uid(),
    'declined',
    null,
    timezone('utc', now())
  )
  on conflict (season_id, profile_id) do update
  set
    status = 'declined',
    registered_at = null,
    decided_at = excluded.decided_at;

  return active_season_id;
end;
$$;

revoke all on function public.set_active_season_participation(boolean) from public, anon;
grant execute on function public.set_active_season_participation(boolean) to authenticated;

create or replace function public.admin_update_participant(
  p_profile_id uuid,
  p_full_name text,
  p_team_name text,
  p_account_eligible boolean,
  p_season_registered boolean,
  p_force_removal boolean default false
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  active_season_id bigint;
  before_profile jsonb;
  pick_count integer;
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Only an admin can update participant accounts.';
  end if;

  if length(trim(coalesce(p_full_name, ''))) = 0
    or length(trim(coalesce(p_team_name, ''))) = 0 then
    raise exception 'Participant full name and team name are required.';
  end if;

  select id into active_season_id
  from public.league_seasons
  where status = 'active';

  if active_season_id is null then
    raise exception 'Activate a season before changing participant registration.';
  end if;

  select to_jsonb(profile) - 'phone_number' - 'phone_carrier'
    into before_profile
  from public.profiles profile
  where profile.id = p_profile_id
  for update;

  if before_profile is null then
    raise exception 'Participant was not found.';
  end if;

  select count(distinct pick.race_id)::integer into pick_count
  from public.picks pick
  join public.races race on race.id = pick.race_id
  where pick.user_id = p_profile_id
    and race.season_id = active_season_id;

  if pick_count > 0
    and (not p_account_eligible or not p_season_registered)
    and not p_force_removal then
    raise exception 'This participant has picks in % active-season race(s). Use forced removal only when you intend to remove them from scoring.', pick_count;
  end if;

  update public.profiles
  set
    full_name = trim(p_full_name),
    team_name = trim(p_team_name),
    is_active = p_account_eligible
  where id = p_profile_id;

  insert into public.season_participants (
    season_id,
    profile_id,
    status,
    registered_at,
    decided_at
  )
  values (
    active_season_id,
    p_profile_id,
    case when p_season_registered then 'registered' else 'declined' end,
    case when p_season_registered then timezone('utc', now()) else null end,
    timezone('utc', now())
  )
  on conflict (season_id, profile_id) do update
  set
    status = excluded.status,
    registered_at = case
      when excluded.status = 'registered'
        then coalesce(public.season_participants.registered_at, excluded.registered_at)
      else null
    end,
    decided_at = excluded.decided_at;

  perform public.write_admin_audit_event(
    'update',
    'participant',
    p_profile_id::text,
    format(
      'Updated participant eligibility and %s registration.%s',
      (select season_year from public.league_seasons where id = active_season_id),
      case when p_force_removal then ' Forced removal was authorized.' else '' end
    ),
    before_profile,
    (
      select (to_jsonb(profile) - 'phone_number' - 'phone_carrier')
        || jsonb_build_object(
          'season_id', active_season_id,
          'season_registered', p_season_registered,
          'active_season_pick_count', pick_count
        )
      from public.profiles profile
      where profile.id = p_profile_id
    )
  );

  return pick_count;
end;
$$;

revoke all on function public.admin_update_participant(uuid, text, text, boolean, boolean, boolean)
from public, anon;
grant execute on function public.admin_update_participant(uuid, text, text, boolean, boolean, boolean)
to authenticated;

create or replace function public.sync_opening_driver_roster(
  p_season_id bigint,
  p_rows jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  target_season public.league_seasons%rowtype;
  created_count integer := 0;
  incoming_count integer;
  item jsonb;
  normalized_names text[];
  result_row_count integer;
  submitted_pick_count integer;
  updated_count integer := 0;
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Only an admin can import the opening driver roster.';
  end if;

  if jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) = 0 then
    raise exception 'Opening roster must contain at least one driver.';
  end if;

  select * into target_season
  from public.league_seasons
  where id = p_season_id
  for update;

  if target_season.id is null or target_season.status = 'completed' then
    raise exception 'Select an active or upcoming season for its opening roster.';
  end if;

  if target_season.status = 'upcoming' and exists (
    select 1
    from public.league_seasons current_season
    where current_season.status = 'active'
      and not exists (
        select 1
        from public.hall_of_fame_seasons hall
        where hall.season_year = current_season.season_year
      )
  ) then
    raise exception 'Finalize the current Hall of Fame standings before preparing the next driver roster.';
  end if;

  select count(*)::integer into result_row_count
  from public.results result_row
  join public.races race on race.id = result_row.race_id
  where race.season_id = target_season.id;

  select count(*)::integer into submitted_pick_count
  from public.picks pick
  join public.races race on race.id = pick.race_id
  where race.season_id = target_season.id;

  if result_row_count > 0 or submitted_pick_count > 0 then
    raise exception 'The opening roster is locked after picks or published results exist.';
  end if;

  select
    count(*)::integer,
    array_agg(lower(trim(row_data.driver_name)) order by row_data.rank)
  into incoming_count, normalized_names
  from jsonb_to_recordset(p_rows)
    as row_data(driver_id bigint, driver_name text, rank integer);

  if incoming_count <> (
    select count(distinct normalized_name)
    from unnest(normalized_names) as normalized_name
  ) then
    raise exception 'Opening roster contains duplicate driver names.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_rows)
      as row_data(driver_id bigint, driver_name text, rank integer)
    where length(trim(coalesce(row_data.driver_name, ''))) = 0
      or row_data.rank is null
      or row_data.rank < 1
      or (
        row_data.driver_id is not null
        and not exists (
          select 1 from public.drivers driver where driver.id = row_data.driver_id
        )
      )
  ) then
    raise exception 'Every roster row requires a driver name and positive rank.';
  end if;

  if (
    select count(distinct row_data.rank)
    from jsonb_to_recordset(p_rows)
      as row_data(driver_id bigint, driver_name text, rank integer)
  ) <> incoming_count then
    raise exception 'Opening roster contains duplicate ranks.';
  end if;

  update public.drivers
  set is_active = false;

  for item in select value from jsonb_array_elements(p_rows)
  loop
    if nullif(item->>'driver_id', '') is not null then
      update public.drivers
      set
        driver_name = trim(item->>'driver_name'),
        championship_points = 0,
        current_standing = (item->>'rank')::integer,
        opening_seed_standing = (item->>'rank')::integer,
        group_number = case
          when (item->>'rank')::integer <= 4 then 1
          when (item->>'rank')::integer <= 8 then 2
          when (item->>'rank')::integer <= 12 then 3
          when (item->>'rank')::integer <= 16 then 4
          when (item->>'rank')::integer <= 20 then 5
          else 6
        end,
        is_active = true
      where id = (item->>'driver_id')::bigint;
      updated_count := updated_count + 1;
    elsif exists (
      select 1
      from public.drivers
      where lower(trim(driver_name)) = lower(trim(item->>'driver_name'))
    ) then
      update public.drivers
      set
        championship_points = 0,
        current_standing = (item->>'rank')::integer,
        opening_seed_standing = (item->>'rank')::integer,
        group_number = case
          when (item->>'rank')::integer <= 4 then 1
          when (item->>'rank')::integer <= 8 then 2
          when (item->>'rank')::integer <= 12 then 3
          when (item->>'rank')::integer <= 16 then 4
          when (item->>'rank')::integer <= 20 then 5
          else 6
        end,
        is_active = true
      where lower(trim(driver_name)) = lower(trim(item->>'driver_name'));
      updated_count := updated_count + 1;
    else
      insert into public.drivers (
        driver_name,
        championship_points,
        current_standing,
        opening_seed_standing,
        group_number,
        is_active
      )
      values (
        trim(item->>'driver_name'),
        0,
        (item->>'rank')::integer,
        (item->>'rank')::integer,
        case
          when (item->>'rank')::integer <= 4 then 1
          when (item->>'rank')::integer <= 8 then 2
          when (item->>'rank')::integer <= 12 then 3
          when (item->>'rank')::integer <= 16 then 4
          when (item->>'rank')::integer <= 20 then 5
          else 6
        end,
        true
      );
      created_count := created_count + 1;
    end if;
  end loop;

  with ranked_inactive as (
    select
      id,
      incoming_count + row_number() over (
        order by current_standing asc, driver_name asc
      )::integer as next_standing
    from public.drivers
    where is_active = false
  )
  update public.drivers driver
  set
    current_standing = ranked_inactive.next_standing,
    group_number = 6
  from ranked_inactive
  where driver.id = ranked_inactive.id;

  update public.league_seasons
  set roster_configured_at = timezone('utc', now())
  where id = target_season.id;

  perform public.write_admin_audit_event(
    'sync_opening_roster',
    'driver_roster',
    target_season.id::text,
    format(
      'Synchronized opening roster: %s updated, %s created, absent drivers made inactive.',
      updated_count,
      created_count
    ),
    null,
    jsonb_build_object(
      'active_driver_count', incoming_count,
      'updated_count', updated_count,
      'created_count', created_count
    )
  );

  return jsonb_build_object(
    'active_driver_count', incoming_count,
    'updated_count', updated_count,
    'created_count', created_count
  );
end;
$$;

