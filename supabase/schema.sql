-- Profiles (extends auth.users)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text check (full_name is null or length(trim(full_name)) between 1 and 100),
  team_name text not null unique check (length(trim(team_name)) between 1 and 100),
  role text not null default 'participant' check (role in ('admin', 'participant')),
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

-- Drivers
create table if not exists public.drivers (
  id bigint generated by default as identity primary key,
  driver_name text not null unique,
  image_url text,
  championship_points integer not null default 0 check (championship_points >= 0),
  current_standing integer not null check (current_standing > 0),
  opening_seed_standing integer check (opening_seed_standing is null or opening_seed_standing > 0),
  group_number smallint not null check (group_number between 1 and 6),
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
