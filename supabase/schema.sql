create or replace function public.assign_race_season_and_round()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.season_id is null then
    select season.id into new.season_id
    from public.league_seasons season
    where season.status = 'active';
  end if;

  if new.season_id is null then
    raise exception 'Create or activate a league season before adding races.';
  end if;

  if new.round_number is null then
    select (coalesce(max(race.round_number), 0) + 1)::smallint into new.round_number
    from public.races race
    where race.season_id = new.season_id;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_assign_race_season_and_round on public.races;
create trigger trg_assign_race_season_and_round
before insert on public.races
for each row execute function public.assign_race_season_and_round();

create or replace function public.is_registered_for_season(
  p_profile_id uuid,
  p_season_id bigint
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.season_participants participant
    join public.profiles profile on profile.id = participant.profile_id
    where participant.profile_id = p_profile_id
      and participant.season_id = p_season_id
      and participant.status = 'registered'
      and profile.is_active = true
  );
$$;

